"""Builds assets/brand-icons.js from ic/social.json and ic/payments.json (glyphs taken from the community icon files used in Figma).
Run: python3 tokens/build_icons.py — never edit brand-icons.js by hand."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
social = {k: v for k, v in json.loads((root / 'ic/social.json').read_text()).items() if not k.startswith('_')}
pay = {k: v for k, v in json.loads((root / 'ic/payments.json').read_text()).items() if not k.startswith('_')}
out = ['/* Generated by tokens/build_icons.py — do not edit by hand. Social: 48x48 glyphs; payments: [viewBox, paths]. */',
       'const SOCIAL=' + json.dumps(social, ensure_ascii=False) + ';',
       'const PAY=' + json.dumps(pay, ensure_ascii=False) + ';']
(root / 'assets/brand-icons.js').write_text('\n'.join(out) + '\n')
print('social', list(social), 'pay', list(pay))
