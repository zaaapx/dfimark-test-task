"""Builds assets/tokens.css from tokens/figma-export.json (exported from the Figma variables and styles).
Run: python3 tokens/build.py — never edit tokens.css by hand."""
import json, math, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
t = json.loads((root / 'tokens/figma-export.json').read_text())
var = lambda n: '--' + re.sub(r'[^a-z0-9]+', '-', n.lower()).strip('-')
def angle(T):
    (a, b, tx), (c, d, ty) = T
    det = a * d - b * c
    inv = lambda u, v: ((d * (u - tx) - b * (v - ty)) / det, (-c * (u - tx) + a * (v - ty)) / det)
    (x0, y0), (x1, y1) = inv(0, .5), inv(1, .5)
    return round(math.degrees(math.atan2(x1 - x0, -(y1 - y0)))) % 360
L = ['/* Generated by tokens/build.py from Figma — do not edit by hand */', ':root{', '  color-scheme:dark;']
L.append('  ' + ''.join(f'{var(k)}:{v};' for k, v in t['color'].items()))
L.append('  ' + ''.join(f'{var(k)}:{v}px;' for k, v in t['size'].items()))
for name, g in t['gradient'].items():
    stops = ','.join(f'var({var(tok)}) {p}%' for p, tok in g['stops'])
    L.append(f'  {var(name.replace("Gradient/", "gradient/").replace(" 75", ""))}:linear-gradient({angle(g["transform"])}deg,{stops});')
fx = {'Elevation/Menu': 'fx-menu', 'Elevation/Dropdown': 'fx-dropdown', 'Elevation/Accent glow': 'fx-glow', 'Blur/Background 8': 'blur-bg-8', 'Blur/Layer 40': 'blur-layer-40'}
L.append('  ' + ''.join(f'--{fx[k]}:{v};' for k, v in t['effect'].items() if k in fx))
L.append('  --ff:Geist,system-ui,sans-serif;--ff-display:Unbounded,Geist,system-ui,sans-serif;')
L.append('}')
(root / 'assets/tokens.css').write_text('\n'.join(L) + '\n')
print('\n'.join(L))
